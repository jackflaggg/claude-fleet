/**
 * Чистое ядро окна лимита Claude.
 *
 * Лимит привязан к аккаунту, а не к проекту: все сессии Claude Code во всех папках жгут одну
 * и ту же квоту. Поэтому окно на борде одно (в шапке), а не по карточке.
 *
 * Точной телеметрии лимита у нас нет, как и у статусов: считаем по локальным транскриптам
 * (`~/.claude/projects/**\/*.jsonl`). У каждой записи ассистента есть `timestamp`, а окно
 * стартует первым запросом после паузы длиннее самого окна - этого достаточно, чтобы знать
 * границу. Расход в токенах отсюда НЕ считаем: сессии из браузера и мобильного в локальные
 * транскрипты не попадают, и число вышло бы заниженным ровно настолько, насколько незаметно.
 *
 * Всё здесь чистое (время приходит параметром), IO живёт в server.js.
 */

/**
 * Разбираем прочитанный кусок прямо в Buffer, не переводя его в строки.
 *
 * Это не микрооптимизация, а разница между «фича бесплатна» и «фича стоит вдвое больше памяти
 * всего процесса»: транскрипты за последние десять часов весят под 50 МБ, декодирование их
 * целиком подбрасывало RSS с 60 до 133 МБ. Нужного текста в них меньше процента - метка
 * времени у записей ассистента. Ищем маркеры буферным indexOf (без аллокаций) и декодируем
 * только саму дату, десяток ASCII-байт.
 *
 * JSON.parse не используем и на строках: он вдвое медленнее сырого поиска (57 мс против 31 мс
 * на живых данных), а метки совпадают полностью.
 */
const NEWLINE = 0x0a;
const QUOTE = 0x22;
const ASSISTANT_MARK = Buffer.from('"type":"assistant"');
const STAMP_MARK = Buffer.from('"timestamp":"');

/**
 * Метка времени запроса в границах одной строки [from, to), иначе null.
 * Считаем только ответы ассистента: записи пользователя и служебные (снапшоты файлов,
 * смены режима) лежат в том же файле, но запросом к модели не являются.
 */
function stampInRange(chunk, from, to) {
  const mark = chunk.indexOf(ASSISTANT_MARK, from);
  if (mark === -1 || mark >= to) return null;
  const at = chunk.indexOf(STAMP_MARK, from);
  if (at === -1 || at >= to) return null;
  const start = at + STAMP_MARK.length;
  const end = chunk.indexOf(QUOTE, start);
  if (end === -1 || end > to) return null;
  // даты в транскрипте всегда ASCII, latin1 тут точнее по смыслу и дешевле utf8
  const ms = Date.parse(chunk.toString('latin1', start, end));
  return Number.isFinite(ms) ? ms : null;
}

/**
 * Складывает метки из куска транскрипта в stamps и возвращает число разобранных байт.
 *
 * Разбираем только до последнего перевода строки: транскрипт дописывают прямо сейчас, и хвост
 * почти всегда обрывается на середине записи. Остаток (chunk.length - разобранное) вызывающая
 * сторона обязана донести до следующего куска, иначе метка на стыке потеряется.
 */
export function collectStamps(chunk, stamps) {
  let start = 0;
  let consumed = 0;
  for (;;) {
    const nl = chunk.indexOf(NEWLINE, start);
    if (nl === -1) return consumed;
    const ts = stampInRange(chunk, start, nl);
    if (ts !== null) stamps.push(ts);
    consumed = nl + 1;
    start = consumed;
  }
}

/**
 * Округляет старт окна вниз до границы выравнивания.
 *
 * Claude открывает окно не по секунде первого запроса, а по ближайшей границе получаса вниз.
 * Сверено с `/usage`: первая активность дня была в 09:32:40, первый ответ в 09:34, а
 * официальный сброс пришёлся на 19:30 - то есть цепочка 09:30 → 14:30 → 19:30. Без
 * выравнивания борд стабильно врал на эти самые минуты в большую сторону.
 */
function alignDown(ts, alignMs) {
  return alignMs > 0 ? Math.floor(ts / alignMs) * alignMs : ts;
}

/**
 * Сворачивает метки в состояние текущего окна: `{ start, last, requests }` либо null.
 *
 * Метки применяются поверх прошлого состояния, поэтому дочитанный хвост файла не требует
 * перечитывать историю целиком. Порядок входа не важен (метки приходят из разных файлов) -
 * сортируем сами; запоздалая метка из уже закрытого окна игнорируется.
 *
 * Выравнивание применяется именно здесь, при открытии окна, а не при показе: от округлённого
 * старта считается и граница следующего окна, иначе метка сразу после сброса попадала бы
 * в уже закрытое окно и цепочка разъезжалась бы дальше с каждым блоком.
 */
export function foldStamps(previous, stamps, windowMs, alignMs = 0) {
  let window = previous;
  for (const ts of [...stamps].sort((a, b) => a - b)) {
    if (!window || ts >= window.start + windowMs) {
      window = { start: alignDown(ts, alignMs), last: ts, requests: 1 };
    } else if (ts >= window.start) {
      window = { start: window.start, last: Math.max(window.last, ts), requests: window.requests + 1 };
    }
  }
  return window;
}

/**
 * Описание окна для борда: когда стартовало, когда закроется, сколько запросов внутри.
 * Оставшееся время фронт считает сам - иначе значение протухало бы между событиями.
 */
export function describeWindow(window, now, windowMs) {
  if (!window) return null;
  const endsAt = window.start + windowMs;
  return {
    startedAt: window.start,
    endsAt,
    requests: window.requests,
    active: now < endsAt,
  };
}

/**
 * Стоит ли вообще открывать файл. Держим запас в два окна: одного мало, чтобы отличить
 * «окно закрылось» от «данных нет» - без предыдущего окна борд не смог бы сказать, что
 * лимит уже сброшен и следующий запрос стартует новое.
 */
export function isFreshTranscript(mtimeMs, now, windowMs) {
  return now - mtimeMs < windowMs * 2;
}
